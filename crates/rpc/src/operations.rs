/// The catalog row for a wire method name.
pub fn spec(method: &str) -> Option<&'static OperationSpec> {
    static INDEX: OnceLock<HashMap<&'static str, &'static OperationSpec>> = OnceLock::new();
    INDEX
        .get_or_init(|| OPERATIONS.iter().map(|op| (op.method, op)).collect())
        .get(method)
        .copied()
}
