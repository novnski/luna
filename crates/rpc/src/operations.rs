//! CORE-01 operation catalog: one reviewed row per shipped RPC method.
//!
//! The legacy method spelling stays the wire name. Each row adds a stable
//! namespaced operation id and version, its kind (query, command or watch),
//! its reply shape, whether it may be addressed to another device, its remote
//! authority and its forwarded-call deadline. Remote policy, device
//! forwarding and forwarded-stream handling read these rows; handlers stay
//! ordinary domain code.
//!
//! Adding a row grants nothing: a new method is local-only until its row names
//! a remote scope, and the engine refuses any method without a row.

use std::collections::HashMap;
use std::sync::OnceLock;

use serde::Serialize;

use crate::methods;
use crate::remote_auth::RemoteScope;

/// Version of the catalog document and of every row's contract fields.
pub const CATALOG_VERSION: u16 = 1;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[serde(rename_all = "camelCase")]
pub enum OperationKind {
    /// Reads state; no side effect beyond bounded caching.
    Query,
    /// Changes state, starts work or spends provider capacity.
    Command,
    /// Subscribes to a value and its changes.
    Watch,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[serde(rename_all = "camelCase")]
pub enum OperationReply {
    /// One `{id, ok}` or `{id, err}` frame.
    Unary,
    /// `{id, item}` frames, then `{id, done: true}`; `{id, cancel: true}` ends it.
    Stream,
    /// A `{id, ok: {"stream": true}}` readiness frame, then as [`Self::Stream`].
    /// Only versioned streams use it: an older client would read the `ok`
    /// frame as a unary reply and drop the stream.
    StreamAfterReady,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[serde(rename_all = "camelCase")]
pub enum OperationTarget {
    /// Always served by the engine that received it.
    Local,
    /// Honors `targetDeviceId` and is forwarded to that device's engine.
    DeviceAddressable,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[serde(tag = "kind", content = "scope", rename_all = "camelCase")]
pub enum OperationAuthority {
    /// Owner IPC only; a remote device session is refused.
    LocalOnly,
    /// The unauthenticated remote handshake (pairing redemption and session
    /// authentication), handled before any scope check.
    RemoteBootstrap,
    /// Callable by a remote device session that holds this scope.
    Remote(RemoteScope),
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[serde(rename_all = "camelCase")]
pub struct OperationSpec {
    /// Legacy wire method name; never renamed.
    pub method: &'static str,
    /// Stable namespaced operation id (`luna.core/<operation>`).
    pub id: &'static str,
    pub version: u16,
    pub kind: OperationKind,
    pub reply: OperationReply,
    pub target: OperationTarget,
    pub authority: OperationAuthority,
    /// Reply deadline when a unary call is forwarded to another device.
    pub forward_deadline_secs: u16,
}

impl OperationSpec {
    /// The scope a remote session needs, or `None` when remote calls are refused.
    pub fn remote_scope(&self) -> Option<RemoteScope> {
        match self.authority {
            OperationAuthority::Remote(scope) => Some(scope),
            OperationAuthority::LocalOnly | OperationAuthority::RemoteBootstrap => None,
        }
    }

    pub fn device_addressable(&self) -> bool {
        self.target == OperationTarget::DeviceAddressable
    }

    pub fn streams(&self) -> bool {
        matches!(
            self.reply,
            OperationReply::Stream | OperationReply::StreamAfterReady
        )
    }
}

#[allow(clippy::too_many_arguments)]
const fn op(
    method: &'static str,
    id: &'static str,
    kind: OperationKind,
    reply: OperationReply,
    target: OperationTarget,
    authority: OperationAuthority,
    forward_deadline_secs: u16,
) -> OperationSpec {
    OperationSpec {
        method,
        id,
        version: 1,
        kind,
        reply,
        target,
        authority,
        forward_deadline_secs,
    }
}

