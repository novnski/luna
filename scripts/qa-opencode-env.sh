#!/usr/bin/env bash
# Create (or refresh) an isolated OpenCode 2 QA profile and print its shell
# exports. Contract: docs/reference/qa-infrastructure.md, "OpenCode QA".
#
#   eval "$(scripts/qa-opencode-env.sh [options] /abs/profile-dir)"
#
# Options:
#   --binary PATH         OpenCode binary or wrapper to pin (default: resolve
#                         like LUNA: OPENCODE_EXECUTABLE, PATH, login shell,
#                         install paths; first OpenCode 2 wins, PD-15)
#   --offline             OPENCODE_DISABLE_MODELS_FETCH=1 (T2 runs)
#   --no-project-config   OPENCODE_DISABLE_PROJECT_CONFIG=1
#   --real-home           keep the real home for ~/.claude and ~/.agents
#                         discovery (default isolates it, QF-02)
#
# The profile's bin/opencode wrapper is what every QA OpenCode process runs
# (T2 rig, harness examples, the LUNA QA app via OPENCODE_EXECUTABLE). It never
# touches the user's OpenCode config, database, credentials, cache or state.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
binary=""
offline=0
no_project=0
real_home=0
profile=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --binary) binary="${2:?--binary needs a path}"; shift 2 ;;
    --offline) offline=1; shift ;;
    --no-project-config) no_project=1; shift ;;
    --real-home) real_home=1; shift ;;
    --print) shift ;;
    -h|--help) sed -n '2,20p' "$0"; exit 0 ;;
    -*) echo "unknown option: $1" >&2; exit 64 ;;
    *) [[ -z "$profile" ]] || { echo "only one profile directory" >&2; exit 64; }; profile="$1"; shift ;;
  esac
done
[[ -n "$profile" ]] || { echo "usage: qa-opencode-env.sh [options] /abs/profile-dir" >&2; exit 64; }

# QF-01: refuse the user's real OpenCode directories, $HOME and /; refuse to
# adopt a non-empty directory that is not already a profile.
profile="$(python3 - "$profile" <<'PY'
import os, pathlib, sys
raw = sys.argv[1]
def reject(message):
    sys.exit('qa-opencode-env: ' + message)
if not raw.startswith('/') or any(c in raw for c in "\n\r'\\\"$`"):
    reject('profile directory must be an absolute path without quotes, $, backticks or newlines')
profile = pathlib.Path(raw).resolve()
home = pathlib.Path.home().resolve()
real = [home / '.config/opencode', home / '.local/share/opencode', home / '.local/share/opencode-v1',
        home / '.cache/opencode', home / '.local/state/opencode', home / '.opencode']
for name in ('XDG_CONFIG_HOME', 'XDG_DATA_HOME', 'XDG_CACHE_HOME', 'XDG_STATE_HOME'):
    value = os.environ.get(name)
    if value and os.path.isabs(value) and not (pathlib.Path(value) / '../luna-qa-opencode-profile.json').exists():
        real.append(pathlib.Path(value).resolve() / 'opencode')
if profile in (home, pathlib.Path('/')) or profile in home.parents:
    reject(f'refusing {profile}: not a disposable profile location')
for directory in real:
    if profile == directory or directory in profile.parents or profile in directory.parents:
        reject(f'refusing {profile}: overlaps the real OpenCode directory {directory}')
if profile.exists() and any(profile.iterdir()) and not (profile / 'luna-qa-opencode-profile.json').exists():
    reject(f'refusing {profile}: non-empty and not an existing QA profile')
print(profile)
PY
)"

# QF-03: resolve the wrapper chain; pin the final native OpenCode 2 binary and
# refuse any hop that rewrites environment (it would undo isolation).
record="$(mktemp "${TMPDIR:-/tmp}/luna-qa-opencode-binary.XXXXXX")"
trap 'rm -f "$record"' EXIT
binary_args=(binary --out "$record")
[[ -z "$binary" ]] || binary_args+=(--path "$binary")
if ! python3 "$repo_root/scripts/qa-opencode-manifest.py" "${binary_args[@]}" >/dev/null; then
  python3 -c 'import json,sys; d=json.load(open(sys.argv[1])); print("qa-opencode-env:", d.get("error")); [print("  considered", c["path"], c.get("version",{}).get("version"), c.get("error") or "") for c in d["considered"]]' "$record" >&2
  exit 69
fi
target="$(python3 - "$record" <<'PY'
import json, sys
record = json.load(open(sys.argv[1]))
bad = [hop['path'] for hop in record['wrapperChain'] if hop.get('mutatesEnv')]
if bad:
    sys.exit('qa-opencode-env: wrapper hop rewrites environment, pass the real binary with --binary: ' + ', '.join(bad))
if any(c in record['final'] for c in "\n\r'\\\"$`"):
    sys.exit('qa-opencode-env: unsafe characters in the binary path')
print(record['final'])
PY
)"

for dir in bin config/opencode data/opencode cache state home tmp; do
  mkdir -p "$profile/$dir"
done
chmod 700 "$profile"

wrapper="$profile/bin/opencode"
{
  printf '#!/bin/sh\n'
  printf '%s\n' '# luna-qa-opencode-profile'
  printf '# luna-qa-opencode-target: %s\n' "$target"
  printf '# Generated by scripts/qa-opencode-env.sh; regenerate instead of editing.\n'
  printf "export XDG_CONFIG_HOME='%s/config'\n" "$profile"
  printf "export XDG_DATA_HOME='%s/data'\n" "$profile"
  printf "export XDG_CACHE_HOME='%s/cache'\n" "$profile"
  printf "export XDG_STATE_HOME='%s/state'\n" "$profile"
  printf "export OPENCODE_CONFIG_DIR='%s/config/opencode'\n" "$profile"
  printf "export OPENCODE_DB='%s/data/opencode/opencode.db'\n" "$profile"
  printf "export TMPDIR='%s/tmp'\n" "$profile"
  printf 'export OPENCODE_DISABLE_AUTOUPDATE=1\n'
  if [[ "$real_home" == 1 ]]; then
    printf 'unset OPENCODE_TEST_HOME\n'
  else
    printf "export OPENCODE_TEST_HOME='%s/home'\n" "$profile"
  fi
  [[ "$offline" == 0 ]] || printf 'export OPENCODE_DISABLE_MODELS_FETCH=1\n'
  [[ "$no_project" == 0 ]] || printf 'export OPENCODE_DISABLE_PROJECT_CONFIG=1\n'
  printf "exec '%s' \"\$@\"\n" "$target"
} >"$wrapper.tmp"
chmod 755 "$wrapper.tmp"
mv "$wrapper.tmp" "$wrapper"

exports="$profile/profile.env"
{
  printf '# Source this file (or eval the script output) to use the QA profile.\n'
  sed -n "s/^export /export /p; s/^unset /unset /p" "$wrapper"
  printf "export OPENCODE_EXECUTABLE='%s'\n" "$wrapper"
  printf "export PATH='%s/bin':\"\$PATH\"\n" "$profile"
} >"$exports"

python3 - "$profile" "$record" "$offline" "$no_project" "$real_home" <<'PY'
import datetime, json, pathlib, sys
profile, record, offline, no_project, real_home = sys.argv[1:]
data = json.load(open(record))
meta = {
    'schema': 'luna-qa-opencode-profile/1',
    'profile': profile,
    'wrapper': str(pathlib.Path(profile) / 'bin/opencode'),
    'target': data['final'],
    'targetSha256': data['finalSha256'],
    'version': data['version']['version'],
    'resolvedFrom': data['resolved'],
    'resolverSource': data['resolverSource'],
    'wrapperChain': data['wrapperChain'],
    'offline': offline == '1',
    'projectConfigDisabled': no_project == '1',
    'homeIsolated': real_home != '1',
    'updatedAt': datetime.datetime.now(datetime.timezone.utc).isoformat().replace('+00:00', 'Z'),
}
(pathlib.Path(profile) / 'luna-qa-opencode-profile.json').write_text(json.dumps(meta, indent=2) + '\n')
PY

cat "$exports"
